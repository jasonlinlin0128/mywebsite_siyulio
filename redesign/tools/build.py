# -*- coding: utf-8 -*-
"""Build the siyulio.com pixel redesign as plain static files.

    py redesign/tools/build.py          # keep the current palette (default 18a)
    py redesign/tools/build.py 18k      # switch palette, rewrite css/palette.css only

Structure (css/site.css) is shared by every 18x palette; colour lives only in css/palette.css.
"""

import os, sys, json

sys.stdout.reconfigure(encoding="utf-8")
TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
import gen, palettes18

V = {s["id"][:3]: s for s in palettes18.VARIANTS}
CUR = os.path.join(TOOLS, "palette.txt")
pick = (
    sys.argv[1]
    if len(sys.argv) > 1
    else (open(CUR).read().strip() if os.path.exists(CUR) else "18a")
)
if pick not in V:
    sys.exit(f"unknown palette {pick}; choose one of {', '.join(V)}")
st = V[pick]
bad = gen.check(st)
if bad:
    sys.exit("contrast check failed:\n" + "\n".join(bad))
open(CUR, "w").write(pick + "\n")


def write(rel, text):
    fp = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(fp), exist_ok=True)
    with open(fp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# ---------------------------------------------------------------- css
bundle = gen.bundle_css(st)
imp, bundle = bundle.split("\n", 1) if bundle.startswith("@import") else ("", bundle)
bundle = bundle.replace(st["title"], "siyulio 像素風")
write(
    "css/palette.css",
    f"/* palette {pick} {st['title'].split(' ', 3)[-1]} — generated by tools/build.py; edit palettes18.py, not this file */\n"
    + gen.tokens_css(st)
    + "\n",
)

